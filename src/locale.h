#ifndef ECLIPSE_LOCALE_H
#define ECLIPSE_LOCALE_H

typedef enum { LANG_TH = 0, LANG_EN = 1, LANG_COUNT } Lang;

typedef enum {
    /* title menu */
    MENU_START, MENU_CONTINUE, MENU_LOAD, MENU_SETTINGS, MENU_EXIT,
    SETTINGS_TITLE, SETTINGS_LANGUAGE, LANG_NAME, MSG_BACK,
    HINT_MENU, HINT_SETTINGS, MSG_NOT_AVAILABLE,
    /* pause menu tabs */
    TAB_INV, TAB_CHAR, TAB_QUEST, TAB_CRAFT, TAB_PET, TAB_SAVE, HINT_PAUSE,
    /* character */
    STAT_LV, STAT_EXP, STAT_HP, STAT_MP, STAT_ATK, STAT_DEF, STAT_STR, STAT_VIT, STAT_AGI,
    STAT_INT, STAT_LUK, STAT_POINTS, STAT_HINT,
    /* inventory */
    INV_EMPTY, ACT_USE, ACT_EQUIP, ACT_SORT, ACT_SPLIT,
    /* quests */
    QST_LOCKED, QST_ACTIVE, QST_DONE, QST_ACCEPTED, QST_COMPLETE, QST_NO_QUEST, QST_REWARD,
    /* npc / shop / crafting */
    NPC_QUEST_GIVER, NPC_MERCHANT, NPC_STATION, NPC_TALK_HINT,
    NPC_QUEST_TALK_1, NPC_QUEST_TALK_2, NPC_MERCHANT_TALK,
    SHOP_BOUGHT, SHOP_NO_GOLD, CRAFT_OK, CRAFT_FAIL, CRAFT_NEED_MATERIALS, CRAFT_NEED_STATION,
    /* pets */
    PET_NONE, PET_FOLLOW, PET_MOUNT_ON, PET_MOUNT_OFF, PET_FED, PET_LOW_FRIENDSHIP,
    /* save */
    SAVE_SLOT, SAVE_EMPTY, SAVE_DONE, LOAD_DONE, LOAD_FAIL,
    /* world */
    REGION_LOCKED, REGION_0, REGION_1, REGION_2, REGION_3, REGION_4, REGION_5,
    BOSS_WARNING, LEVEL_UP, DEFEAT_MONSTER, PLAYER_DEFEATED, HARVEST_OK, HARVEST_WAIT,
    DUNGEON_ENTER, STAT_SPENT, HINT_GAME, NO_TARGET,
    STR_COUNT
} StrId;

void        loc_set(Lang lang);
Lang        loc_get_lang(void);
const char *loc_str(StrId id);

#endif
