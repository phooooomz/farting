#!/usr/bin/env python3
"""Generate src/font_data.c: 8-bit alpha bitmap atlas for ASCII + Thai.

Usage: python3 tools/gen_font.py assets/font/Sarabun-Regular.ttf 16 src/font_data.c
Each glyph is stored with its bounding box relative to the pen origin
(on the baseline). Zero-advance glyphs (Thai vowels/tone marks) are
flagged as marks and are drawn at their base glyph's origin.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

def ranges():
    yield from range(0x20, 0x7F)          # ASCII
    yield from range(0x0E01, 0x0E5C)      # Thai block

def main():
    ttf, size, out = sys.argv[1], int(sys.argv[2]), sys.argv[3]
    font = ImageFont.truetype(ttf, size)
    entries, blob = [], bytearray()
    for cp in ranges():
        ch = chr(cp)
        adv = font.getlength(ch)
        x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        is_mark = adv == 0 and w > 0
        data_off = len(blob)
        if w > 0 and h > 0:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
            blob += img.tobytes()
        entries.append((cp, round(adv), x0, y0, w, h, 1 if is_mark else 0, data_off))

    with open(out, "w", encoding="utf-8") as f:
        f.write("/* Generated by tools/gen_font.py from Sarabun-Regular.ttf (SIL OFL 1.1). Do not edit. */\n")
        f.write('#include "font.h"\n\n')
        f.write("const uint8_t font_bitmap[%d] = {\n" % max(1, len(blob)))
        for i in range(0, len(blob), 16):
            f.write("  " + ",".join("%d" % b for b in blob[i:i+16]) + ",\n")
        f.write("};\n\n")
        f.write("const FontGlyph font_glyphs[%d] = {\n" % len(entries))
        for cp, adv, x0, y0, w, h, mark, off in entries:
            f.write("  {0x%04X, %d, %d, %d, %d, %d, %d, %d},\n" % (cp, adv, x0, y0, w, h, mark, off))
        f.write("};\n\nconst int font_glyph_count = %d;\nconst int font_size = %d;\n" % (len(entries), size))
    print("glyphs:", len(entries), "bitmap bytes:", len(blob))

if __name__ == "__main__":
    main()
